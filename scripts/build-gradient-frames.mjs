/*
 * Captures every selectable frame for every brand, and writes the manifest the
 * UI reads.
 *
 * The "Edit background" control on /work lets a visitor put any of these frames
 * behind a card, or run the animation instead. Those options have to be real
 * files rather than something rendered on demand: rendering ten previews per
 * card would mean loading the Lottie player and playing ten instances just to
 * choose one, which is the cost the stills exist to avoid.
 *
 * The manifest is generated rather than hand-kept, so the list the picker
 * offers cannot drift from what is actually on disk.
 *
 *   node scripts/build-gradient-frames.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

const FRAMES = [0, 60, 120, 180, 240, 300, 360, 420, 480, 540];
const OUT_DIR = "public/images/frames";

/*
 * inUse is the frame a card shows before a visitor chooses; null plays the
 * animation. All four run by default — the stills are what a visitor can switch
 * to, not what they start on.
 */
const BRANDS = [
  { key: "pura", label: "Pura", src: "public/animations/Gradient BG 3.json", inUse: null },
  { key: "adib", label: "ADIB", src: "public/animations/gradient-adib.json", inUse: null },
  { key: "clientele", label: "Clientele", src: "public/animations/gradient-clientele.json", inUse: null },
  { key: "nedbank", label: "Nedbank", src: "public/animations/gradient-nedbank.json", inUse: null },
  { key: "absa", label: "ABSA", src: "public/animations/gradient-absa.json", inUse: null },
];

/* The sampled frames, with a brand's chosen frame swapped in over its nearest
   neighbour — so every brand offers the same number of options while the one
   in use is always among them. */
function framesFor(inUse) {
  if (inUse === null || FRAMES.includes(inUse)) return [...FRAMES];
  const nearest = FRAMES.reduce((best, f) =>
    Math.abs(f - inUse) < Math.abs(best - inUse) ? f : best,
  );
  return FRAMES.map((f) => (f === nearest ? inUse : f)).sort((a, b) => a - b);
}

mkdirSync(OUT_DIR, { recursive: true });

const manifest = BRANDS.map((brand) => {
  const frames = framesFor(brand.inUse);
  for (const frame of frames) {
    execFileSync(
      "node",
      ["scripts/capture-frame.mjs", brand.src, String(frame), `${OUT_DIR}/${brand.key}-${frame}.svg`],
      { stdio: "pipe" },
    );
  }
  console.log(`${brand.label.padEnd(10)} ${frames.length} frames: ${frames.join(", ")}`);
  return { ...brand, frames };
});

writeFileSync(
  "lib/gradients.ts",
  `/*
 * GENERATED by scripts/build-gradient-frames.mjs — do not edit by hand.
 *
 * Every frame listed here exists as a file under public/images/frames/. Run the
 * script again after adding a brand or changing which frames are offered.
 */

export type Gradient = {
  key: string;
  label: string;
  /** The Lottie source, for viewers who choose to run it rather than a still. */
  animation: string;
  /** Selectable frames, in order. */
  frames: number[];
  /** The frame a card shows until a viewer picks otherwise. Null plays the animation. */
  defaultFrame: number | null;
};

export const GRADIENTS: Record<string, Gradient> = {
${manifest
  .map(
    (b) => `  ${b.key}: {
    key: "${b.key}",
    label: "${b.label}",
    animation: "${b.src.slice("public".length)}",
    frames: [${b.frames.join(", ")}],
    defaultFrame: ${b.inUse === null ? "null" : b.inUse},
  },`,
  )
  .join("\n")}
};

/** The still for one frame of one brand. */
export function frameSrc(key: string, frame: number): string {
  return \`/images/frames/\${key}-\${frame}.svg\`;
}
`,
);
console.log("\nwrote lib/gradients.ts");
